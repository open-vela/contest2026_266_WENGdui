#define NVIC_SYSH_PRIORITY_DEFAULT      0x80 /* 取中值作为默认优先级 */
#define NVIC_SYSH_PRIORITY_MAX          0x00 /* 0 为最高优先级 */
#define NVIC_SYSH_PRIORITY_STEP         0x20 /* 相邻优先级步进 */

